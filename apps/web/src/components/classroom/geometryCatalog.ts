export type GeoHighlightPart = 'none' | 'vertices' | 'edges' | 'faces';

export interface GeometryShapeMeta {
  id: GeometryShapeId;
  label: string;
  shortLabel: string;
  dimension: '2D' | '3D';
  colorHex: number;
  faces: string;
  edges: string;
  vertices: string;
  primaryFormulaLabel: string;
  primaryFormula: string;
  secondaryFormulaLabel: string;
  secondaryFormula: string;
  vertexSpeech: string;
  edgeSpeech: string;
  faceSpeech: string;
  overviewSpeech: string;
  /** Key 3D anchor points for the live animated pointer arrow */
  pointers: {
    vertex: [number, number, number];
    edge: [number, number, number];
    face: [number, number, number];
    vertexLabel?: string;
    edgeLabel?: string;
    faceLabel?: string;
  };
  /** Highlightable vertex positions to light up as glowing spheres */
  vertexPoints: [number, number, number][];
}

function regularPolygonPts(sides: number, radius: number, z = 0.08): [number, number, number][] {
  const pts: [number, number, number][] = [];
  for (let i = 0; i < sides; i++) {
    const a = (i / sides) * Math.PI * 2 + Math.PI / 2;
    pts.push([Math.cos(a) * radius, Math.sin(a) * radius, z]);
  }
  return pts;
}

